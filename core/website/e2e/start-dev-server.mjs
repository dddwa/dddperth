#!/usr/bin/env node
/**
 * Boots the Vite dev server for the e2e suites, fully isolated from local dev.
 *
 * Isolation is the point. The suites use their own wrangler config
 * (`conference/wrangler/e2e/e2e.jsonc`, selected via `WRANGLER_CONFIG`),
 * which lives in its own directory — and the Cloudflare Vite plugin resolves
 * `.dev.vars` relative to the active wrangler config's directory. So this
 * script writes `conference/wrangler/e2e/.dev.vars` and the developer's
 * `conference/wrangler/.dev.vars` is never read, written, or restored.
 *
 * That replaces an earlier version which mutated the real `.dev.vars` in
 * place and restored it on exit. The restore was best-effort: a `kill -9`, a
 * crash, or an IDE stop skipped it and left SESSIONIZE_* pointing at a dead
 * fixture port, which then broke the next `pnpm start` for non-obvious
 * reasons. Nothing to restore is strictly better than restoring carefully.
 *
 * What isolation buys:
 *   - `pnpm start` (port 3800) and the suites (port 3801) run side by side.
 *   - Sessionize always resolves to the committed fixtures, so no test run
 *     ever touches the real API — this is still a wrapper rather than
 *     Playwright's `globalSetup` because Playwright starts `webServer`
 *     *before* `globalSetup` runs, and the Cloudflare plugin reads Worker
 *     vars at boot and ignores `process.env` (both verified).
 *   - `E2E_DATE_OVERRIDE` is scoped here, so the `__devDateOverride` cookie
 *     is inert during ordinary local dev and can't shadow the admin date
 *     override in the UI.
 */
import { spawn } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { startSessionizeFixtureServer, SESSIONIZE_FIXTURE_PORT } from './fixtures/sessionize-server.ts'

const here = dirname(fileURLToPath(import.meta.url))
const websiteDir = join(here, '..')
const repoRoot = join(websiteDir, '..', '..')

/** Own directory => own .dev.vars. Never the developer's. */
const e2eWranglerDir = join(repoRoot, 'conference', 'wrangler', 'e2e')
const e2eDevVarsPath = join(e2eWranglerDir, '.dev.vars')

/** Own port, so we can never collide with (or attach to) `pnpm start`. */
const port = process.env.E2E_PORT ?? '3801'

const fixtureServer = await startSessionizeFixtureServer()

mkdirSync(e2eWranglerDir, { recursive: true })
writeFileSync(
    e2eDevVarsPath,
    [
        '# Generated by e2e/start-dev-server.mjs on every run. Gitignored.',
        '# Never edit by hand, and never point these at the real Sessionize API.',
        'SESSION_SECRET=e2e-placeholder-secret-not-used-in-production',
        `WEB_URL=http://localhost:${port}`,
        // Enables the __devDateOverride cookie. Scoped to this file so the
        // cookie does nothing during ordinary local dev.
        'E2E_DATE_OVERRIDE=true',
        `SESSIONIZE_2026_SESSIONS=${fixtureServer.url}`,
        `SESSIONIZE_2026_ALL_SESSIONS=${fixtureServer.url}`,
        '',
    ].join('\n'),
)

console.log(`[e2e] Sessionize fixtures on ${fixtureServer.url} (port ${SESSIONIZE_FIXTURE_PORT})`)
console.log(`[e2e] dev server on :${port} using conference/wrangler/e2e/e2e.jsonc`)

// Invoke Vite's binary directly rather than via `pnpm vite`. Playwright's
// `webServer` and the visual-regression script both spawn this without a
// login shell, so a version-manager shim on PATH (mise, asdf, volta) may not
// resolve — `pnpm` is not guaranteed to be runnable here even when it works
// in an interactive terminal. The local binary always is.
// pnpm may hoist to the workspace root or keep a project-local bin, so check
// both rather than assuming a layout.
const viteBin = [
    join(websiteDir, 'node_modules', '.bin', 'vite'),
    join(repoRoot, 'node_modules', '.bin', 'vite'),
].find((candidate) => existsSync(candidate))

if (!viteBin) {
    console.error('[e2e] Could not find the vite binary in node_modules/.bin — run `pnpm install` first.')
    process.exit(1)
}

const vite = spawn(viteBin, ['--port', port, ...process.argv.slice(2)], {
    cwd: websiteDir,
    stdio: 'inherit',
    env: { ...process.env, WRANGLER_CONFIG: 'e2e/e2e.jsonc' },
})

for (const signal of ['SIGINT', 'SIGTERM']) {
    process.on(signal, () => {
        void fixtureServer.close()
        vite.kill(signal)
        process.exit(0)
    })
}

vite.on('exit', (code) => {
    void fixtureServer.close()
    process.exit(code ?? 0)
})
