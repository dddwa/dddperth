#!/usr/bin/env node
/**
 * Boots the Vite dev server for the e2e suites, fully isolated from local dev.
 *
 * Isolation is the point. The suites use their own wrangler config
 * (`conference/wrangler/e2e/e2e.jsonc`, selected via `WRANGLER_CONFIG`),
 * which lives in its own directory — and the Cloudflare Vite plugin resolves
 * `.dev.vars` relative to the active wrangler config's directory. So this
 * script writes `conference/wrangler/e2e/.dev.vars` and the developer's
 * `conference/wrangler/.dev.vars` is never read, written, or restored.
 *
 * That replaces an earlier version which mutated the real `.dev.vars` in
 * place and restored it on exit. The restore was best-effort: a `kill -9`, a
 * crash, or an IDE stop skipped it and left SESSIONIZE_* pointing at a dead
 * fixture port, which then broke the next `pnpm start` for non-obvious
 * reasons. Nothing to restore is strictly better than restoring carefully.
 *
 * What isolation buys:
 *   - `pnpm start` (port 3800) and the suites (port 3801) run side by side.
 *   - Sessionize always resolves to the committed fixtures, for every year,
 *     so no test run ever touches the real API — this is still a wrapper
 *     rather than Playwright's `globalSetup` because Playwright starts
 *     `webServer` *before* `globalSetup` runs, and the Cloudflare plugin reads
 *     Worker vars at boot and ignores `process.env` (both verified).
 *   - `E2E_DATE_OVERRIDE` is scoped here, so the `__devDateOverride` cookie
 *     is inert during ordinary local dev and can't shadow the admin date
 *     override in the UI.
 */
import { spawn } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { startSessionizeFixtureServer, SESSIONIZE_FIXTURE_PORT } from './fixtures/sessionize-server.ts'

/**
 * Years given fixture Sessionize endpoints. Interception is host-based and
 * already covers every year, but the app checks its *configured* endpoint
 * before fetching — so a year whose config leaves the endpoint undefined
 * renders "no agenda yet" regardless. Kept as literals rather than imported
 * from `routes.ts`: this file runs under plain Node, which can't resolve the
 * `@conference/*` TypeScript path aliases that module now depends on.
 */
const FIXTURE_ENDPOINT_YEARS = ['2025', '2026']

const here = dirname(fileURLToPath(import.meta.url))
const websiteDir = join(here, '..')

/**
 * Own directory => own .dev.vars. Never the developer's.
 *
 * A fork runs this from `core/website/` against `conference/` two levels up;
 * `ddd-core` standalone runs from `website/` against `conference-stub/` one
 * level up. Resolved by looking, so the suite works in either layout.
 */
const e2eWranglerDir = [
    join(websiteDir, '..', '..', 'conference', 'wrangler', 'e2e'),
    join(websiteDir, '..', 'conference-stub', 'wrangler', 'e2e'),
].find((dir) => existsSync(join(dir, '..')))

if (!e2eWranglerDir) {
    console.error(
        '[e2e] No wrangler directory found. Expected ../../conference/wrangler (fork) or ' +
            '../conference-stub/wrangler (ddd-core standalone), relative to the website project.',
    )
    process.exit(1)
}

const e2eDevVarsPath = join(e2eWranglerDir, '.dev.vars')

/** Own port, so we can never collide with (or attach to) `pnpm start`. */
const port = process.env.E2E_PORT ?? '3801'

const fixtureServer = await startSessionizeFixtureServer()

mkdirSync(e2eWranglerDir, { recursive: true })
writeFileSync(
    e2eDevVarsPath,
    [
        '# Generated by e2e/start-dev-server.mjs on every run. Gitignored.',
        '# Never edit by hand, and never point these at the real Sessionize API.',
        'SESSION_SECRET=e2e-placeholder-secret-not-used-in-production',
        `WEB_URL=http://localhost:${port}`,
        // Enables the __devDateOverride cookie. Scoped to this file so the
        // cookie does nothing during ordinary local dev.
        'E2E_DATE_OVERRIDE=true',
        // Interception: the worker rewrites any sessionize.com request to the
        // fixtures (app/lib/sessionize-fixture-fetch.server.ts). Host-based, so
        // it covers every year — including 2021-2025, which hardcode their
        // Sessionize URLs in config and therefore have no env override to set.
        // Without this they reached the live API.
        `SESSIONIZE_FIXTURE_URL=${fixtureServer.url}`,
        // Configuration: 2026 leaves its endpoints undefined for env injection,
        // and the voting loader checks `allSessionsEndpoint` is set *before*
        // fetching anything — so interception alone leaves /voting rendering
        // its "not configured" state. These two do different jobs; both are
        // needed. The value only has to be a Sessionize URL for the
        // interceptor to catch it.
        ...FIXTURE_ENDPOINT_YEARS.flatMap((year) => [
            `SESSIONIZE_${year}_SESSIONS=https://sessionize.com/api/v2/e2e-fixture`,
            `SESSIONIZE_${year}_ALL_SESSIONS=https://sessionize.com/api/v2/e2e-fixture`,
        ]),
        '',
    ].join('\n'),
)

console.log(`[e2e] Sessionize fixtures on ${fixtureServer.url} (port ${SESSIONIZE_FIXTURE_PORT})`)
console.log(`[e2e] dev server on :${port} using ${join(e2eWranglerDir, 'e2e.jsonc')}`)

// Invoke Vite's binary directly rather than via `pnpm vite`. Playwright's
// `webServer` and the visual-regression script both spawn this without a
// login shell, so a version-manager shim on PATH (mise, asdf, volta) may not
// resolve — `pnpm` is not guaranteed to be runnable here even when it works
// in an interactive terminal. The local binary always is.
// pnpm may hoist to the workspace root or keep a project-local bin, so check
// both rather than assuming a layout.
const viteBin = [
    join(websiteDir, 'node_modules', '.bin', 'vite'),
    // Workspace root: one level up in ddd-core standalone, two in a fork.
    join(websiteDir, '..', 'node_modules', '.bin', 'vite'),
    join(websiteDir, '..', '..', 'node_modules', '.bin', 'vite'),
].find((candidate) => existsSync(candidate))

if (!viteBin) {
    console.error('[e2e] Could not find the vite binary in node_modules/.bin — run `pnpm install` first.')
    process.exit(1)
}

const vite = spawn(viteBin, ['--port', port, ...process.argv.slice(2)], {
    cwd: websiteDir,
    stdio: 'inherit',
    env: { ...process.env, WRANGLER_CONFIG: 'e2e/e2e.jsonc' },
})

for (const signal of ['SIGINT', 'SIGTERM']) {
    process.on(signal, () => {
        void fixtureServer.close()
        vite.kill(signal)
        process.exit(0)
    })
}

vite.on('exit', (code) => {
    void fixtureServer.close()
    process.exit(code ?? 0)
})
